QTY = re.compile(r"\(?\s*\d+(?:\.\d+)?\s*(?:인|종|벌|개입|개|매|마|입|쌍|조|구|장|도|ml|mL|ML|L|kg|g|cm|티백|P|p|%|세트)\)?")


def clean_title(title):
    title = re.sub(r"\([^)]*\d[^)]*\)", " ", title)            # (2개입) (지름 3cm)
    title = re.sub(r"(\d)\s*(단|층|폭|색)", lambda m: NUM.get(m.group(1), "") + m.group(2), title)
    title = re.sub(r"(?<![가-힣])일(단|층|폭|색)", "", title)
    title = re.sub(r"1\+1", " ", title)
    title = QTY.sub(" ", title)
    title = re.sub(r"\d+", " ", title)
    title = re.sub(r"\s+", " ", title).strip()
    words, out = title.split(" "), []
    for w in words:
        if w in ("호", "시", "중") and out:
            continue
        if not out or out[-1] != w:
            out.append(w)
    return " ".join(out).replace(" 세트 세트", " 세트")


